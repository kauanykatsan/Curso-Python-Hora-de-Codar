#CRIANDO CONJUNTOS: SINTAXE E MÉTODOS 

#SET()

#conjuntos(set) em Python são coleções desordenadas de elementos únicos, criando com {} ou set()
#Não aceita elementos duplicados


conjunto = {1,2,3,4}

print(conjunto)
conjunto_de_lista = set({1,2,3,})
print(conjunto_de_lista)

print(len(conjunto_de_lista))
print(4 in conjunto_de_lista)
print(1 in conjunto_de_lista)
